param(
    [Parameter(Mandatory)][string]$ResourceRoot,
    [Parameter(Mandatory)][string]$Output
)
$ErrorActionPreference = 'Stop'

# The runtime is a DEX/JAR, not an APK. Compile its small string-only resource
# set into Java so UI rendering needs neither APK resource IDs nor disk reads.
function JavaLiteral([string]$value) {
    return '"' + $value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t') + '"'
}
function ReadStrings([string]$path) {
    $settings = [Xml.XmlReaderSettings]::new()
    $settings.DtdProcessing = [Xml.DtdProcessing]::Prohibit
    $reader = [Xml.XmlReader]::Create($path, $settings)
    try {
        $document = [Xml.XmlDocument]::new()
        $document.Load($reader)
    } finally { $reader.Dispose() }
    if ($document.DocumentElement.Name -ne 'resources') { throw "Expected resources root: $path" }
    $strings = [ordered]@{}
    foreach ($node in $document.DocumentElement.ChildNodes) {
        if ($node.NodeType -ne [Xml.XmlNodeType]::Element) { continue }
        $name = $node.GetAttribute('name')
        if ($node.LocalName -ne 'string' -or $name -cnotmatch '^[a-z][a-z0-9_]*$' -or $strings.Contains($name) -or $node.SelectNodes('*').Count) {
            throw "Invalid or duplicate plain string resource in ${path}: $name"
        }
        # Support the escapes used in Android strings.xml; reject unknown ones.
        $value = [regex]::Replace($node.InnerText, '\\(.)', {
            param($match)
            switch -CaseSensitive ($match.Groups[1].Value) {
                'n' { "`n" } 't' { "`t" } 'r' { "`r" } '\' { '\' } '"' { '"' } "'" { "'" }
                default { throw "Unsupported string escape in ${path}: $($match.Value)" }
            }
        })
        if ([string]::IsNullOrEmpty($value)) { throw "Empty string resource in ${path}: $name" }
        $strings.Add($name, $value)
    }
    return ,$strings
}

$defaults = ReadStrings (Join-Path $ResourceRoot 'values/strings.xml')
$sets = @($defaults)
$tags = @('en')
foreach ($directory in Get-ChildItem -LiteralPath $ResourceRoot -Directory | Sort-Object Name) {
    if ($directory.Name -eq 'values') { continue }
    if ($directory.Name -cnotmatch '^values-([a-z]{2,3})(?:-r([A-Z]{2}))?$') {
        throw "Unsupported ART string resource directory: $($directory.Name)"
    }
    $tag = $Matches[1]
    if ($Matches[2]) { $tag += '-' + $Matches[2] }
    $localized = ReadStrings (Join-Path $directory.FullName 'strings.xml')
    foreach ($key in $localized.Keys) {
        if (-not $defaults.Contains($key)) { throw "Unknown ART string resource in $($directory.Name): $key" }
        $pattern = '%(?:[1-9][0-9]*\$)?[sd]|%%'
        $expected = @([regex]::Matches($defaults[$key], $pattern) | ForEach-Object Value | Sort-Object)
        $actual = @([regex]::Matches($localized[$key], $pattern) | ForEach-Object Value | Sort-Object)
        if (($expected -join '|') -cne ($actual -join '|')) { throw "Mismatched format placeholders in $($directory.Name): $key" }
    }
    $tags += $tag
    $sets += $localized
}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by BuildArtStrings.ps1. Edit res/values*/strings.xml instead.')
$lines.Add('package com.trebledot.stone.runtime;')
$lines.Add('final class ArtStrings {')
$index = 0
foreach ($key in $defaults.Keys) { $lines.Add("    static final int $key = $index;"); $index++ }
$lines.Add('    static final String[] tags = {' + (($tags | ForEach-Object { JavaLiteral $_ }) -join ', ') + '};')
$lines.Add('    static final String[][] values = {')
foreach ($set in $sets) {
    $lines.Add('        {')
    foreach ($key in $defaults.Keys) {
        $lines.Add('            ' + $(if ($set.Contains($key)) { JavaLiteral $set[$key] } else { 'null' }) + ',')
    }
    $lines.Add('        },')
}
$lines.Add('    };')
$lines.Add('    private ArtStrings() { }')
$lines.Add('}')
$target = [IO.Path]::GetFullPath($Output)
New-Item -ItemType Directory -Force -Path ([IO.Path]::GetDirectoryName($target)) | Out-Null
[IO.File]::WriteAllLines($target, $lines, [Text.UTF8Encoding]::new($false))
